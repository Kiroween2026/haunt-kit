/** The CSS for tokens.css. */
export function themeCss(): string {
  const lines: string[] = [
    "/* GENERATED by `pnpm --filter @haunt-kit/ui gen:tokens` from src/tokens.ts. Do not edit by hand. */",
    "",
    ":root,",
    "[data-theme] {",
    ...Object.entries(shared).map(([k, v]) => `  --hk-${k}: ${v};`),
    "}",
  ];
  for (const theme of THEME_NAMES) {
    lines.push("", `[data-theme="${theme}"] {`);
    for (const token of COLOR_TOKENS) lines.push(`  --hk-color-${token}: ${colors[theme][token]};`);
    lines.push(`  --hk-font-heading: ${fonts[theme].heading};`);
    lines.push(`  --hk-font-body: ${fonts[theme].body};`);
    lines.push(`  --hk-shadow-glow: ${shadows[theme].glow};`);
    lines.push(`  --hk-shadow-card: ${shadows[theme].card};`);
    lines.push("}");
  }
  return lines.join("\n") + "\n";
}

// ---------- contrast (WCAG 2.x) ----------

function channel(v: number): number {
  const s = v / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const n = parseInt(hex.slice(1), 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

/** WCAG contrast ratio, 1 to 21. */
export function contrast(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

